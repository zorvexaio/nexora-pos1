// دالة عامة لترجمة نص عربي حرفي وقت التشغيل — تُستخدم لرسائل alert()/confirm()
// التي لا تمر بالـ DOM إطلاقاً (نوافذ المتصفح الأصلية) ولذلك لا يقدر
// applyStaticTranslations (الذي يمسح عناصر body فقط) يترجمها لاحقاً. تستخدم
// نفس قاموس STATIC_TRANSLATIONS المستخدم للنصوص الثابتة بالصفحات القديمة.
function ts(arabicText) {
  const lang = document.documentElement.getAttribute('data-lang') || 'ar';
  if (lang === 'ar') return arabicText;
  const dict = STATIC_TRANSLATIONS[lang];
  return (dict && dict[arabicText]) || arabicText;
}

function applyStaticTranslations(lang) {
  const dictionary = { ...(STATIC_TRANSLATIONS[lang] || {}), ...((RAW_TRANSLATIONS && RAW_TRANSLATIONS[lang]) || {}) };
  if (!document.documentElement.dataset.titleAr) document.documentElement.dataset.titleAr = document.title;
  document.title = (dictionary && dictionary[document.documentElement.dataset.titleAr]) || document.documentElement.dataset.titleAr;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = []; let node;
  while ((node = walker.nextNode())) nodes.push(node);
  nodes.forEach((textNode) => {
    if (!STATIC_ORIGINALS.has(textNode)) STATIC_ORIGINALS.set(textNode, textNode.nodeValue);
    const originalValue = STATIC_ORIGINALS.get(textNode);
    const original = originalValue.trim();
    if (!original) return;
    if (dictionary && dictionary[original]) {
      textNode.nodeValue = originalValue.replace(original, dictionary[original]);
      return;
    }
    // Translate known Arabic phrases inside dynamic strings as well (for example:
    // "الحالة: معتمدة | الإجمالي: 100.00"). Longest phrases first prevents
    // partial replacements from corrupting longer translations.
    let translatedValue = originalValue;
    const entries = Object.entries(dictionary || {})
      .filter(([k]) => /[\u0600-\u06FF]/.test(k))
      .sort((a,b) => b[0].length - a[0].length);
    for (const [ar, translated] of entries) {
      if (!ar || ar === translated || !translated) continue;
      translatedValue = translatedValue.split(ar).join(translated);
    }
    textNode.nodeValue = translatedValue;
  });
  document.querySelectorAll('input[placeholder]').forEach((input) => {
    const original = input.dataset.i18nPlaceholderSource || input.getAttribute('placeholder');
    if (!input.dataset.i18nPlaceholderSource) input.dataset.i18nPlaceholderSource = original;
    input.setAttribute('placeholder', (dictionary && dictionary[original]) || original);
  });
}

async function initI18n() {
  let lang = 'ar';
  try {
    if (window.api && window.api.language) {
      lang = (await window.api.language.get()) || 'ar';
    }
  } catch (err) {
    // نستمر باللغة الافتراضية إن تعذّر القراءة (مثلاً قبل تجهيز قاعدة البيانات)
  }
  applyTranslations(lang);

  const switcher = document.getElementById('langSwitcher');
  if (switcher) {
    switcher.value = lang;
    switcher.addEventListener('change', async () => {
      const newLang = switcher.value;
      applyTranslations(newLang);
      if (window.api && window.api.language) {
        await window.api.language.set(newLang);
      }
    });
  }

  // السبب الأصلي لبقاء بعض الكلمات بالعربي بعد تبديل اللغة: applyStaticTranslations
  // كانت تُترجم محتوى الصفحة لحظة الاستدعاء فقط (عند فتح الصفحة أو عند تبديل اللغة
  // نفسها). أي محتوى يُبنى ديناميكياً بعد تلك اللحظة (تحديث قائمة، فتح دورة رواتب،
  // نتيجة بحث...) كان يُدرَج بنصه العربي الخام ولا يُعاد فحصه أبداً. هذا المراقب
  // يعيد تطبيق الترجمة تلقائياً كلما أُضيف محتوى جديد لصفحة body، بغض النظر متى
  // أو من أي دالة أُضيف. (يراقب childList فقط، وليس characterData، حتى لا يعيد
  // تشغيل نفسه بلا نهاية عندما يُعدّل نص العقد التي ترجمها للتو.)
  let pendingRetranslate = null;
  const observer = new MutationObserver((mutations) => {
    const hasNewNodes = mutations.some((m) => m.addedNodes && m.addedNodes.length > 0);
    if (!hasNewNodes) return;
    if (pendingRetranslate) return;
    pendingRetranslate = Promise.resolve().then(() => {
      pendingRetranslate = null;
      const currentLang = document.documentElement.getAttribute('data-lang') || 'ar';
      applyStaticTranslations(currentLang);
    });
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

document.addEventListener('DOMContentLoaded', initI18n);
