// Runtime messages (alert/confirm) do not pass through the DOM translation
// pipeline. Keep native browser behavior, but translate known Arabic runtime
// messages before they reach the user. This also covers dynamic messages whose
// Arabic prefix is followed by a server error, e.g. "تعذر الحفظ: ...".
function translateRuntimeMessage(value) {
  const text = String(value ?? '');
  const lang = document.documentElement.getAttribute('data-lang') || 'ar';
  if (lang === 'ar') return text;
  const dictionary = {
    ...(STATIC_TRANSLATIONS[lang] || {}),
    ...((RAW_TRANSLATIONS && RAW_TRANSLATIONS[lang]) || {})
  };
  let result = text;
  const entries = Object.entries(dictionary)
    .filter(([source, translated]) => source && translated && source !== translated && /[\u0600-\u06FF]/.test(source))
    .sort((a, b) => b[0].length - a[0].length);
  for (const [source, translated] of entries) result = result.split(source).join(translated);
  return result;
}

